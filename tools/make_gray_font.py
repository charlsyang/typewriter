#!/usr/bin/env python3
"""Convert a TTF into an anti-aliased font header for the Inkplate's 3-bit mode.

For the sleep screen's highlights (Libron). Unlike make_font.py's 1-bit GFX fonts:
  - glyphs keep their anti-aliasing: 4 bits of ink per pixel (0 none, 15 full)
  - advances are in 1/16 px, so rounding doesn't add up across a line
  - kerning: the font's pair adjustments (GPOS 'kern'), flattened with HarfBuzz
    for the characters the device has, in 1/16 px; pairs under 1/4 px are dropped

The character set and byte mapping are make_font.py's (ASCII, typographic
punctuation at 0x80+, Latin-1), so tw::fontByte() works for both.

Usage: tools/.venv/bin/python tools/make_gray_font.py NAME SIZE FONT_FILE [--line-spacing L]
Example: tools/make_gray_font.py Libron52 52 fonts/Libron-Regular.ttf
"""
import argparse
import os

import uharfbuzz as hb
from PIL import Image, ImageDraw, ImageFont

from make_font import byte_map

ROOT = os.path.join(os.path.dirname(__file__), "..")
OUT_DIR = os.path.join(ROOT, "lib", "Typewriter", "src", "fonts")
MIN_KERN_16THS = 4  # drop pair adjustments smaller than 1/4 px


def rasterize(font, cp):
    """Return (nibbles, width, height, x_offset, y_offset) for one code point."""
    ch = chr(cp)
    left, top, right, bottom = font.getbbox(ch, anchor="ls")
    if right <= left or bottom <= top:
        return [], 0, 0, 0, 0
    w, h = right - left, bottom - top
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
    px = img.load()
    return [round(px[x, y] * 15 / 255) for y in range(h) for x in range(w)], w, h, left, top


def pack(nibbles):
    """Two pixels per byte, high nibble first, continuous across rows."""
    out = bytearray((len(nibbles) + 1) // 2)
    for i, v in enumerate(nibbles):
        out[i // 2] |= v << 4 if i % 2 == 0 else v
    return out


def kern_pairs(path, size, slots):
    """{(left byte, right byte): adjustment in 1/16 px} from the font's kerning."""
    face = hb.Face(hb.Blob.from_file_path(path))
    font = hb.Font(face)
    scale = size * 16 / face.upem

    def width(s, kern):
        buf = hb.Buffer()
        buf.add_str(s)
        buf.guess_segment_properties()
        hb.shape(font, buf, {"kern": kern, "liga": False})
        return sum(p.x_advance for p in buf.glyph_positions)

    chars = [(b, chr(cp)) for b, cp in slots if cp is not None]
    pairs = {}
    for lb, lc in chars:
        for rb, rc in chars:
            d = round((width(lc + rc, True) - width(lc + rc, False)) * scale)
            if abs(d) >= MIN_KERN_16THS:
                pairs[(lb, rb)] = d
    return pairs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("size", type=int)
    ap.add_argument("font_file")
    ap.add_argument("--line-spacing", type=float, default=1.45)
    args = ap.parse_args()

    font = ImageFont.truetype(args.font_file, args.size)
    slots = byte_map()
    bitmap, glyphs, missing = bytearray(), [], []
    for byte, cp in slots:
        if cp is None:
            glyphs.append((len(bitmap), 0, 0, 0, 0, 0, byte, None))
            continue
        if font.getmask(chr(cp)).getbbox() is None and cp not in (0x20, 0xA0):
            missing.append(f"U+{cp:04X}")
        nibbles, w, h, xo, yo = rasterize(font, cp)
        adv16 = round(font.getlength(chr(cp)) * 16)
        glyphs.append((len(bitmap), w, h, adv16, xo, yo, byte, cp))
        bitmap += pack(nibbles)
    pairs = kern_pairs(args.font_file, args.size, slots)

    ascent, descent = font.getmetrics()
    ident = args.name
    src = os.path.basename(args.font_file)
    lines = [
        f"// Generated by tools/make_gray_font.py {args.name} {args.size} {src} --line-spacing {args.line_spacing}",
        f"// Source: {src} (SIL Open Font License 1.1), see fonts/Libron-LICENSE.txt",
        "#pragma once",
        "#include <Text.h>",
        "",
        f"static const uint8_t {ident}Bitmaps[] = {{",
    ]
    lines += ["  " + ",".join(f"0x{b:02X}" for b in bitmap[i:i + 24]) + "," for i in range(0, len(bitmap), 24)]
    lines += ["};", "", f"static const tw::GrayGlyph {ident}Glyphs[] = {{"]
    for off, w, h, adv16, xo, yo, byte, cp in glyphs:
        label = "unused" if cp is None else (f"U+{cp:04X}" if cp > 0x7E else repr(chr(cp)))
        lines.append(f"  {{{off}, {w}, {h}, {adv16}, {xo}, {yo}}},  // 0x{byte:02X} {label}")
    lines += ["};", "", f"static const tw::KernPair {ident}Kerning[] = {{"]
    items = sorted(pairs.items())
    for i in range(0, len(items), 8):
        lines.append("  " + " ".join(f"{{0x{l:02X},0x{r:02X},{d}}}," for (l, r), d in items[i:i + 8]))
    lines += ["};", ""]
    y_advance = round(args.size * args.line_spacing)
    lines.append(f"static const tw::GrayFont {ident} = {{{ident}Bitmaps, {ident}Glyphs, 0x20, 0xFF, {y_advance}, "
                 f"{ascent}, {descent}, {ident}Kerning, {len(items)}}};")
    lines.append("")

    path = os.path.join(OUT_DIR, f"{ident}.h")
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print(f"{path}: {len(bitmap)} bitmap bytes, {len(items)} kerning pairs")
    if missing:
        print("glyphs not in font (drawn blank):", " ".join(missing))


if __name__ == "__main__":
    main()
