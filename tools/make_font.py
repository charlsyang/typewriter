#!/usr/bin/env python3
"""Convert a TTF into an Adafruit GFX font header for the Inkplate.

Glyphs are rasterized exactly like tools/preview_fonts.py (FreeType anti-aliasing,
then a black/white cutoff), so the device matches the previews.

GFX fonts index glyphs by a single byte range. Byte values map to characters as:
  0x20-0x7E  ASCII
  0x80-0x9F  typographic punctuation outside Latin-1 (see EXTRA), in list order
  0xA0-0xFF  Latin-1 Supplement (same as the Unicode code point)
The header also emits a lookup table so the firmware can map UTF-8 code points
to these bytes.

Usage: tools/.venv/bin/python tools/make_font.py NAME SIZE [--weight W] [--cutoff C]
Example: tools/make_font.py Duo40 40 --weight 400 --cutoff 64
"""
import argparse
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.join(os.path.dirname(__file__), "..")
FONT_FILE = os.path.join(ROOT, "fonts", "iAWriterDuoV.ttf")
OUT_DIR = os.path.join(ROOT, "lib", "Typewriter", "src", "fonts")

# Code points outside Latin-1 that show up in prose, placed at bytes 0x80+.
EXTRA = [
    0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E,  # ‘ ’ ‚ “ ” „
    0x2013, 0x2014, 0x2026, 0x2022, 0x2032, 0x2033,  # – — … • ′ ″
    0x2039, 0x203A, 0x20AC, 0x2122, 0x2190, 0x2192,  # ‹ › € ™ ← →
    0x2191, 0x2193, 0x2212, 0x2248, 0x2260, 0x2264,  # ↑ ↓ − ≈ ≠ ≤
    0x2265,                                          # ≥
]


def byte_map():
    """Return [(byte, code point)] for every glyph slot from 0x20 to 0xFF."""
    slots = [(b, b) for b in range(0x20, 0x7F)]
    slots.append((0x7F, None))
    for i in range(0x20):
        slots.append((0x80 + i, EXTRA[i] if i < len(EXTRA) else None))
    slots += [(b, b) for b in range(0xA0, 0x100)]
    return slots


def load_font(size, weight):
    font = ImageFont.truetype(FONT_FILE, size)
    axes = font.get_variation_axes()
    font.set_variation_by_axes([weight if a["name"] == b"Weight" else a["default"] for a in axes])
    return font


def rasterize(font, cp, cutoff):
    """Return (bits, width, height, x_offset, y_offset, x_advance) for one code point."""
    ch = chr(cp)
    advance = round(font.getlength(ch))
    left, top, right, bottom = font.getbbox(ch, anchor="ls")
    if right <= left or bottom <= top:
        return [], 0, 0, 0, 0, advance
    w, h = right - left, bottom - top
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
    px = img.load()
    bits = [1 if px[x, y] >= cutoff else 0 for y in range(h) for x in range(w)]
    return bits, w, h, left, top, advance


def pack(bits):
    """Pack bits MSB-first, continuous across rows, as Adafruit GFX expects."""
    out = bytearray((len(bits) + 7) // 8)
    for i, bit in enumerate(bits):
        if bit:
            out[i // 8] |= 0x80 >> (i % 8)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("size", type=int)
    ap.add_argument("--weight", type=int, default=400)
    ap.add_argument("--cutoff", type=int, default=128)
    ap.add_argument("--line-spacing", type=float, default=1.5)
    args = ap.parse_args()

    font = load_font(args.size, args.weight)
    bitmap = bytearray()
    glyphs = []
    missing = []
    for byte, cp in byte_map():
        if cp is None:
            glyphs.append((len(bitmap), 0, 0, 0, 0, 0, byte, None))
            continue
        if font.getmask(chr(cp)).getbbox() is None and cp != 0x20 and cp != 0xA0:
            missing.append(f"U+{cp:04X}")
        bits, w, h, xo, yo, adv = rasterize(font, cp, args.cutoff)
        glyphs.append((len(bitmap), w, h, adv, xo, yo, byte, cp))
        bitmap += pack(bits)

    if len(bitmap) > 0xFFFF:
        raise SystemExit(f"bitmap is {len(bitmap)} bytes; GFX offsets are 16-bit")

    ascent, descent = font.getmetrics()
    ident = args.name
    lines = [
        f"// Generated by tools/make_font.py {args.name} {args.size} --weight {args.weight} "
        f"--cutoff {args.cutoff}",
        f"// Source: iA Writer Duo (SIL Open Font License 1.1), see fonts/iA-Fonts-LICENSE.md",
        "#pragma once",
        "#include <Inkplate.h>",
        "",
        f"static const uint8_t {ident}Bitmaps[] = {{",
    ]
    lines += ["  " + ",".join(f"0x{b:02X}" for b in bitmap[i:i + 24]) + "," for i in range(0, len(bitmap), 24)]
    lines.append("};")
    lines.append("")
    lines.append(f"static const GFXglyph {ident}Glyphs[] = {{")
    for off, w, h, adv, xo, yo, byte, cp in glyphs:
        label = "unused" if cp is None else (f"U+{cp:04X}" if cp > 0x7E else repr(chr(cp)))
        lines.append(f"  {{{off}, {w}, {h}, {adv}, {xo}, {yo}}},  // 0x{byte:02X} {label}")
    lines.append("};")
    lines.append("")
    y_advance = round(args.size * args.line_spacing)
    lines.append(f"static const GFXfont {ident} = {{(uint8_t *){ident}Bitmaps, (GFXglyph *){ident}Glyphs, "
                 f"0x20, 0xFF, {y_advance}}};")
    lines.append(f"static const int16_t {ident}Ascent = {ascent};")
    lines.append(f"static const int16_t {ident}Descent = {descent};")
    lines.append("")

    os.makedirs(OUT_DIR, exist_ok=True)
    path = os.path.join(OUT_DIR, f"{ident}.h")
    with open(path, "w") as f:
        f.write("\n".join(lines))

    # The code point table is the same for every font, so it lives in its own header.
    extra_path = os.path.join(OUT_DIR, "FontExtraCodepoints.h")
    with open(extra_path, "w") as f:
        f.write("// Generated by tools/make_font.py: code points stored at font bytes 0x80+.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("static const uint16_t FONT_EXTRA_CODEPOINTS[] = {\n")
        f.write("  " + ", ".join(f"0x{cp:04X}" for cp in EXTRA) + ",\n};\n")
        f.write(f"static const int FONT_EXTRA_COUNT = {len(EXTRA)};\n")

    print(f"{path}: {len(bitmap)} bitmap bytes, advance of 'n' = {font.getlength('n'):.2f}px")
    if missing:
        print("glyphs not in font (drawn blank):", " ".join(missing))


if __name__ == "__main__":
    main()
